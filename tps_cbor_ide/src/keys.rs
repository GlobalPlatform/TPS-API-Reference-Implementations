/// The caveat `UI_DESIGN.md:125` asks to be shown when a key has been generated.
///
/// Verbatim from the specification, **including its two spelling and punctuation faults**
/// ("cryptgraphically", and no full stop before "use"). A specified string is a specified string:
/// correcting it here would put the implementation and the document out of step over something no
/// test could later tell apart from a paraphrase. Pinned by a test below, and raised in `PLAN.md`
/// rather than silently fixed — `UI_DESIGN.md` is the specification and is not edited to match the
/// implementation.
///
/// `tps_cbor_core::cose::keygen`'s module documentation already records why the warning is true:
/// key generation draws from the OS CSPRNG through the RustCrypto curve crates, and on a platform
/// whose entropy source is weak or unseeded that is all the assurance there is.
pub const RANDOMNESS_WARNING: &str = "Warning: keys generated by this platform may not be \
     cryptgraphically random use for test purposes only.";

/// Whether the private-value box starts out hidden.
///
/// A named constant rather than a `true` at each of the two places that need it, because those two
/// have to agree and the failure if they do not is silent: `Ide::new` creates the box masked, and
/// the paint-time sync re-masks it on **every** selection change — a box masked only on creation
/// would keep the reveal the user asked for on one key and apply it to the next key they clicked.
///
/// `true` because `UI_DESIGN.md:130` asks for a *reveal* button, which makes hidden the resting
/// state and showing a deliberate act. A masked input also keeps its value out of the clipboard
/// (`gpui-base/src/input/base/mod.rs:105-107` disable Copy and Cut), which is a property worth
/// having rather than one to work around.
pub const MASKED: bool = true;

/// What a dialog's OK button did: `Err` leaves the dialog open with the message shown in it.
pub type Accepted = std::result::Result<(), String>;

/// The selected key's detail rows (`UI_DESIGN.md:128-130`).
///
/// Extracted once per selection change rather than per frame, and the private value with it:
/// [`tps_cbor_core::keystore::KeyStore::load`] reads a file and returns a `Zeroizing` buffer, and
/// doing that from a render path would put private material through a hot loop for no gain.
///
/// Every field is already a `String`, because the pane cannot hold a decoded [`CoseKey`]: the type
/// borrows from the buffer it was decoded out of, and that buffer is dropped — and zeroed — at the
/// end of [`KeyDetail::of`].
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct KeyDetail {
    /// The alias in the key store.
    pub alias: String,
    /// `"EC2"`, `"OKP"` or `"Symmetric"`.
    pub key_type: String,
    /// The curve's registry spelling, for the key types that have one.
    pub curve: Option<String>,
    /// The algorithm, named where this crate recognises the identifier and numbered where it does
    /// not — see [`cose::algorithm_name`].
    pub algorithm: Option<String>,
    /// The `kid` the key carries, hex-encoded. `None` for every key this tool generates.
    pub key_id: Option<String>,
    /// The `d` or `k` value, hex-encoded, for the masked box `UI_DESIGN.md:130` asks for.
    ///
    /// `None` for a public-only key, which is the case `a_key_with_no_private_part_shows_no_masked_row`
    /// pins: a masked box with nothing behind it invites a click that reveals nothing.
    pub private: Option<String>,
}

impl KeyDetail {
    /// Describe the key `meta` names, given its stored COSE_Key bytes.
    ///
    /// Takes the bytes rather than the store so that the exposure is visible at the call site: the
    /// caller holds a `Zeroizing` buffer and hands it over for exactly as long as this call. What
    /// comes back is a hex `String` of the private value when there is one, which is a plain
    /// allocation — the residual exposure `PLAN.md` records, and the price `UI_DESIGN.md:130`'s
    /// reveal button asks for.
    ///
    /// Falls back to `meta` alone when the bytes do not decode. A key store whose index and files
    /// disagree is a broken store, but refusing to name the key at all would leave the user with a
    /// row they cannot select and no way to delete it.
    pub fn of(meta: &KeyMeta, bytes: &[u8]) -> Self {
        let mut detail = Self {
            alias: meta.alias.clone(),
            key_type: meta.key_type.clone(),
            curve: meta.curve.clone(),
            algorithm: meta
                .algorithm
                .map(|value| match cose::algorithm_name(value) {
                    Some(name) => format!("{name} ({value})"),
                    None => value.to_string(),
                }),
            key_id: None,
            private: None,
        };
        if let Ok(key) = tps_cose::decode_cose_key(bytes) {
            detail.key_id = cose::key_id(&key).map(hex);
            detail.private = cose::key_private(&key).map(hex);
        }
        detail
    }
}

/// Lowercase hex, unseparated.
///
/// Not [`tps_cbor_core::convert::hex_dump`], which is the offset-prefixed grid the hex view wants:
/// a key identifier is a short value on one line of a detail row, and an address column beside it
/// would be noise.
fn hex(bytes: &[u8]) -> String {
    use std::fmt::Write as _;
    bytes.iter().fold(String::new(), |mut out, byte| {
        let _ = write!(out, "{byte:02x}");
        out
    })
}

/// An encryption algorithm, as a row in the `Encrypt` dropdown.
///
/// A wrapper rather than an impl on [`EncryptAlgorithm`] itself, because the trait belongs to
/// gpui-component and the type to `tps_cose` — and because `tps_cbor_core/CLAUDE.md` forbids UI
/// types in the core crate, which is the same rule seen from the other side.
///
/// The `Value` is the algorithm, so [`SelectState::selected_value`] hands back something
/// [`ops::encrypt`] takes directly and there is no name-to-algorithm lookup to get wrong.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AlgChoice(pub EncryptAlgorithm);

impl SelectItem for AlgChoice {
    type Value = EncryptAlgorithm;

    fn title(&self) -> SharedString {
        ops::encrypt_algorithm_name(self.0).into()
    }

    fn value(&self) -> &Self::Value {
        &self.0
    }
}

/// Every encryption algorithm, as dropdown rows.
///
/// Built from [`ops::ENCRYPT_ALGORITHMS`], which exists for exactly this. The old frontend
/// hardcoded `A128Gcm` in three places (`EncryptPanel.tsx:85-88` among them), so the list being
/// derived rather than written out is the regression this phase is specifically against — and
/// `the_algorithm_list_offers_all_nine` pins it.
pub fn alg_choices() -> Vec<AlgChoice> {
    ops::ENCRYPT_ALGORITHMS
        .iter()
        .copied()
        .map(AlgChoice)
        .collect()
}

/// A kind of key the Generate Key form can mint.
///
/// `UI_DESIGN.md:124` asks for "any of the key types supported by TPS COSE", which is two families
/// reached through two different core functions —
/// [`KeyStore::generate`](tps_cbor_core::keystore::KeyStore::generate) for a keypair and
/// [`KeyStore::generate_symmetric`](tps_cbor_core::keystore::KeyStore::generate_symmetric) for a
/// shared key — so the dropdown needs one type spanning both.
///
/// All nine symmetric entries are offered, not the three distinct key *lengths*, because the
/// algorithm is recorded in the key: `generate_symmetric` writes `alg` into the COSE_Key's common
/// header, so an `A128GCM` key and an `AES-CCM-16-64-128` key differ in their metadata even though
/// both are 16 bytes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NewKeyKind {
    /// A keypair.
    Asymmetric(GenKeyKind),
    /// A shared symmetric key sized for an encryption algorithm.
    Symmetric(EncryptAlgorithm),
}

impl NewKeyKind {
    /// The dropdown label.
    ///
    /// The asymmetric half delegates to [`GenKeyKind::label`] rather than restating it, so the
    /// strings the core crate already reviewed ("EC2 / P-256 (ES256)") are the ones shown. The
    /// symmetric half names the key length, because that is the only thing distinguishing two
    /// otherwise interchangeable AES-CCM entries to a user who is choosing one.
    pub fn label(self) -> String {
        match self {
            Self::Asymmetric(kind) => kind.label().to_owned(),
            Self::Symmetric(alg) => format!(
                "Symmetric / {} ({} bytes)",
                ops::encrypt_algorithm_name(alg),
                ops::symmetric_key_len(alg)
            ),
        }
    }
}

impl SelectItem for NewKeyKind {
    type Value = Self;

    fn title(&self) -> SharedString {
        self.label().into()
    }

    fn value(&self) -> &Self::Value {
        self
    }
}

/// Every key kind the form offers, keypairs first.
pub fn new_key_kinds() -> Vec<NewKeyKind> {
    GenKeyKind::ALL
        .into_iter()
        .map(NewKeyKind::Asymmetric)
        .chain(
            ops::ENCRYPT_ALGORITHMS
                .iter()
                .copied()
                .map(NewKeyKind::Symmetric),
        )
        .collect()
}

/// A refusal from an OK press, remembered together with the alias it was about.
///
/// The pairing is the point. A message that outlives the text it describes is worse than no
/// message: after `bad/alias` is rejected the user's next act is to edit the box, and a refusal
/// still reading "invalid alias 'bad/alias'" under a box now holding `my-es256` reads as the new
/// alias having been rejected too. So [`refusal_for`] shows it only while the box still holds the
/// alias it concerns, and editing clears it.
///
/// Done this way — compared at render — rather than by subscribing to the input's change event,
/// because the dialog builder is a `Fn` render closure with nowhere to keep a subscription: it is
/// rebuilt whenever the dialog layer repaints, and a `cx.subscribe` inside it would be re-made
/// every frame. An `Rc<RefCell<..>>` created *outside* the closure is the one piece of state these
/// dialogs can own, and this keeps it to one.
type Refusal = Rc<RefCell<Option<(String, String)>>>;

/// The refusal to show, if it is still about what the alias box holds.
fn refusal_for(refusal: &Refusal, alias: &Entity<InputState>, cx: &App) -> Option<String> {
    let typed = alias.read(cx).value();
    refusal
        .borrow()
        .as_ref()
        .filter(|(about, _)| about.as_str() == typed.as_ref())
        .map(|(_, message)| message.clone())
}

/// `UI_DESIGN.md:124`'s "select key type and name" form.
///
/// `accept` is handed the alias exactly as typed — unvalidated, because
/// [`validate_alias`](tps_cbor_core::keystore::validate_alias) is the one place that rule lives and
/// it runs inside the key store on every operation. A refusal comes back as `Err` and the dialog
/// stays open with it shown, which is what makes a mistyped alias correctable rather than a silent
/// no-op.
pub fn generate_key_dialog<F>(keystore_dir: String, window: &mut Window, cx: &mut App, accept: F)
where
    F: Fn(&str, NewKeyKind, &mut Window, &mut App) -> Accepted + 'static,
{
    // Before `open_dialog`, and captured: see the module docs on the builder being a render
    // closure. Everything below belongs to *this* opening of the dialog.
    let alias = cx.new(|cx| InputState::new(window, cx).placeholder("my-es256"));
    let kinds = new_key_kinds();
    let kind = cx.new(|cx| {
        SelectState::new(kinds, Some(IndexPath::default().row(0)), window, cx)
            // 14 rows, which is a scroll rather than a hunt. Already the default; stated because
            // the alternative was considered and the list's length is the reason.
            .searchable(false)
    });
    let error: Refusal = Rc::new(RefCell::new(None));
    let first_paint = Cell::new(true);
    // `Rc` because the builder is `Fn`: each rebuild installs a fresh `on_ok` closure, and each of
    // those needs its own handle on the callback.
    let accept = Rc::new(accept);

    window.open_alert_dialog(cx, move |alert, window, cx| {
        if first_paint.replace(false) {
            alias.focus_handle(cx).focus(window, cx);
        }

        let message = refusal_for(&error, &alias, cx);
        let form = v_flex()
            .gap_2()
            .w_full()
            .child(field_label("Alias", cx))
            .child(Input::new(&alias))
            .child(field_label("Key type", cx))
            .child(
                // No `menu_width`, deliberately. Its default is `Length::Auto`, which `Select`
                // renders as the *trigger's* measured width (`select.rs:642-645`) — which is what
                // is wanted. A definite `relative(1.)` looks like the same thing and is not: the
                // menu is `deferred` into the window's overlay, so a fraction resolves against
                // that and came out at under half the trigger, truncating every label past
                // "OKP / Ed25519…". For the symmetric kinds that is the part that matters, since
                // the key length in the label is what tells two AES-CCM entries apart.
                Select::new(&kind).id("new-key-kind").menu_max_h(px(280.)),
            )
            .when_some(message, |this, message| {
                this.child(div().text_sm().text_color(cx.theme().danger).child(message))
            });

        let on_ok = {
            let (alias, kind, error, accept) =
                (alias.clone(), kind.clone(), error.clone(), accept.clone());
            move |_: &ClickEvent, window: &mut Window, cx: &mut App| {
                let typed = alias.read(cx).value().to_string();
                // Unreachable while the state is seeded with row 0, and still answered: a `Select`
                // with no selection is a legitimate state of the widget, and a silent `return
                // false` would make OK look broken.
                let Some(kind) = kind.read(cx).selected_value().copied() else {
                    *error.borrow_mut() = Some((typed.clone(), "Choose a key type.".to_owned()));
                    window.refresh();
                    return false;
                };
                match accept(&typed, kind, window, cx) {
                    Ok(()) => true,
                    Err(reason) => {
                        // Paired with the alias it is about; see [`Refusal`].
                        *error.borrow_mut() = Some((typed, reason));
                        // The refusal is only in the `RefCell`; without this the dialog stays open
                        // showing the form exactly as it was, which reads as OK doing nothing.
                        window.refresh();
                        false
                    }
                }
            }
        };

        alert
            .title("Generate key")
            .description(format!("The key is written to {keystore_dir}."))
            .confirm()
            .ok_text("Generate")
            .width(px(420.))
            .child(form)
            .on_ok(on_ok)
    });
}

/// The alias prompt File->Open raises for a COSE key (`UI_DESIGN.md:119`).
///
/// Separate from [`generate_key_dialog`] rather than a mode of it: there is no key type to choose —
/// the file has one already — and the dialog's whole job is to say plainly what OK will do, which is
/// write someone's key material into the key store. A user who opened a key file to *look* at it
/// should be able to see that and press Cancel.
pub fn import_key_dialog<F>(
    file: String,
    keystore_dir: String,
    suggested: String,
    window: &mut Window,
    cx: &mut App,
    accept: F,
) where
    F: Fn(&str, &mut Window, &mut App) -> Accepted + 'static,
{
    let alias = cx.new(|cx| {
        InputState::new(window, cx)
            .placeholder("alias")
            .default_value(suggested)
    });
    let error: Refusal = Rc::new(RefCell::new(None));
    let first_paint = Cell::new(true);
    let accept = Rc::new(accept);

    window.open_alert_dialog(cx, move |alert, window, cx| {
        if first_paint.replace(false) {
            alias.focus_handle(cx).focus(window, cx);
        }

        let message = refusal_for(&error, &alias, cx);
        let form = v_flex()
            .gap_2()
            .w_full()
            .child(field_label("Alias", cx))
            .child(Input::new(&alias))
            .when_some(message, |this, message| {
                this.child(div().text_sm().text_color(cx.theme().danger).child(message))
            });

        let on_ok = {
            let (alias, error, accept) = (alias.clone(), error.clone(), accept.clone());
            move |_: &ClickEvent, window: &mut Window, cx: &mut App| {
                let typed = alias.read(cx).value().to_string();
                match accept(&typed, window, cx) {
                    Ok(()) => true,
                    Err(reason) => {
                        // Paired with the alias it is about; see [`Refusal`].
                        *error.borrow_mut() = Some((typed, reason));
                        window.refresh();
                        false
                    }
                }
            }
        };

        alert
            .title("Import key")
            .description(format!(
                // Names the two buttons by the text they actually carry, which is why `Import`
                // rather than `OK`: `ok_text` below renames the confirm button, and a description
                // that says "OK" sends the reader looking for a button that is not there.
                "{file} holds a COSE key. Import copies it into the key store at \
                 {keystore_dir}; Cancel leaves the store untouched."
            ))
            .confirm()
            .ok_text("Import")
            .width(px(480.))
            .child(form)
            .on_ok(on_ok)
    });
}

/// `UI_DESIGN.md:125`'s caveat, shown after a key has been generated.
///
/// The second of the two dialogs `:124-125` asks for, and it follows the generation rather than
/// being a checkbox in the form: the sentence is about the key that now exists, not a condition on
/// making one. Nothing comes back from it — it is information, and the user's only answer is to
/// have read it.
///
/// Note what is *missing*: no `.confirm()`. An `AlertDialog` already
/// carries an OK button and no Cancel (`gpui-component/src/dialog/alert_dialog.rs:78-80`), and
/// `.confirm()` is what *adds* the Cancel — which here would offer a choice between dismissing a
/// warning and dismissing it, over a key that has already been written to disk.
///
/// The caller raises it through [`Window::defer`] rather than calling it from inside the generate
/// dialog's `on_ok`: that `on_ok` is about to return `true`, which closes "the" dialog by popping
/// the last one opened, and a warning opened first would be the one popped.
pub fn warn_randomness(window: &mut Window, cx: &mut App) {
    window.open_alert_dialog(cx, |alert, _, _| {
        alert
            .title("Key generated")
            .description(RANDOMNESS_WARNING)
            .ok_text("OK")
            .width(px(420.))
    });
}

/// A form field's caption, in the muted colour the right pane's labels use.
fn field_label(text: &'static str, cx: &App) -> AnyElement {
    div()
        .text_sm()
        .text_color(cx.theme().muted_foreground)
        .child(text)
        .into_any_element()
}

// There is deliberately no `applies(artefact, meta)` wrapper here, though
// `cose::artefact::eligible` would make one trivial and an earlier sketch of this pane had it. It
// would have greyed `Sign` for a key that cannot sign — and that is precisely the wrong behaviour:
// a greyed button says only "not now", while pressing it reports `UnsupportedSign`'s own sentence,
// which is the undifferentiated `InvalidKey` answer this phase exists to replace. The eligibility
// predicate is for keeping [`cose::identify`]'s trial pass off keys that cannot apply, which is
// work the user never asked for; refusing a key the user explicitly chose is work they did.

/// `key_type` and `curve` as one line, for the key list's rows.
///
/// `"EC2 / P-256"`, or just `"Symmetric"` for a key with no curve.
pub fn describe_kind(meta: &KeyMeta) -> String {
    match &meta.curve {
        Some(curve) => format!("{} / {}", meta.key_type, curve),
        None => meta.key_type.clone(),
    }
}

/// Whether a decoded key carries private material, for a caller that has the bytes.
///
/// Used by the import path to say in a diagnostic whether what was imported can sign, which is the
/// difference between a usable key and one that can only verify.
pub fn has_private(key: &CoseKey<'_>) -> bool {
    cose::key_has_private(key)
}

