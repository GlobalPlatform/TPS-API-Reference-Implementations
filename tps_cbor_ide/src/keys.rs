//! The key store's vocabulary and its two dialogs (`UI_DESIGN.md:118-130`).
//!
//! What this module is *not* is the pane. The plan called this file `key_pane.rs` and put the key
//! list and the key detail in it; they ended up as [`crate::Ide`] methods instead — `keys_page` and
//! `cose_options`, beside `diagnostics_page`, `trace_page` and `cbor_options` — because every page
//! in this application is a method on the root view, and a page that renders from a `&mut
//! Context<Ide>` cannot be one of those without taking the root view as a parameter. Moving two
//! pages out would have cost a module that depends on `Ide` to render and gained nothing. Recorded
//! as a divergence in `PLAN.md`.
//!
//! What is left here is everything that is *not* a page, which turns out to be the part worth
//! separating:
//!
//! * [`KeyDetail`] — the detail rows, extracted once per selection change rather than per frame.
//! * [`AlgChoice`] and [`NewKeyKind`] — the two dropdowns' items, which exist because
//!   [`SelectState`] needs its values behind a trait and the core crate's enums cannot implement a
//!   UI trait.
//! * [`RANDOMNESS_WARNING`] — `UI_DESIGN.md:125`'s sentence, verbatim.
//! * [`generate_key_dialog`], [`import_key_dialog`] and [`warn_randomness`] — the three modal
//!   forms.
//!
//! ## The dialog seam
//!
//! Both dialogs take an `accept` callback returning [`Accepted`], and neither knows that a key
//! store exists. That split is not tidiness: `on_ok` returning `false` **keeps the dialog open**
//! (`gpui-component/src/dialog/dialog.rs:88-91`), which is exactly what a rejected
//! [`tps_cbor_core::keystore::validate_alias`] wants — so the dialog has to be able to show a
//! refusal and stay up, and the thing that refuses is the key store. `Err(message)` is that
//! refusal, displayed in the form; `Ok(())` closes.
//!
//! ## Why the entities are created before the dialog is opened
//!
//! `WindowExt::open_dialog`'s builder is a **render closure, not a constructor**: it is `Fn`, not
//! `FnOnce`, and runs again whenever the dialog layer rebuilds (`window_ext.rs:40-48` says so
//! outright). An `InputState` created with `cx.new(...)` inside it would be replaced on every
//! rebuild, losing everything the user had typed. So the alias box and the picker are built first
//! and their handles captured, and the initial focus is taken only on the first invocation, behind
//! a [`Cell`] guard — focusing unconditionally would steal focus back from whatever the user moved
//! to.

