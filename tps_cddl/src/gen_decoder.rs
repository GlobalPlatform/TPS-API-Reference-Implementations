//! Phase 5: generate a `tps_minicbor`-based CBOR decoder from a CDDL schema.
//!
//! The public entry point is [`gen_decoder`].  It returns a Rust source string
//! that the caller can write to a file or print to stdout.

use std::collections::HashSet;

use crate::{
    Config,
    ast::{Cddl, GrpEntBody, Occur, Rule, RuleBody, Type, Type2, Value as CddlValue},
    feature_manifest::FeatureManifest,
    gen_common::{
        GenError, MapKeyRepr, RuleKind, array_group, cbor_constraint, cbor_field_rust_type,
        check_features_resolved, classify, collect_ordered, default_constraint,
        default_value_rust_literal, emit_regexp_todo, is_prelude, map_group, map_key_repr,
        prune_disabled_features, rule_needs_lifetime, to_pascal_case, type2_item_pattern,
        type2_major_key, type2_to_rust_type, union_variant_name,
    },
};


// ─── Public entry point ────────────────────────────────────────────────────────

/// Generate a Rust decoder source string for the given CDDL schema.
///
/// If `root` is `Some(name)`, only that rule and its transitive dependencies
/// are emitted.  If `root` is `None`, all rules are emitted.
///
/// Every `.feature` (RFC 9165 §4) name reachable in the emitted rule closure
/// must be resolved by `manifest`; an unresolved name is a hard error (see
/// [`GenError::UnresolvedFeatures`]). Choices resolved `disabled` are omitted
/// from the emitted union entirely; choices resolved `enabled` are emitted as
/// if unconstrained.
///
/// The returned string is valid Rust source that depends on the `tps_minicbor` crate.
///
/// # Examples
///
/// ```
/// use tps_cddl::{lex, build_cddl, gen_decoder, Config, FeatureManifest};
///
/// let pairs = lex("person = { name: tstr, age: uint }").unwrap();
/// let schema = build_cddl(pairs).unwrap();
/// let manifest = FeatureManifest::from_json("{}").unwrap();
/// let code = gen_decoder(&schema, None, &Config::strict(), &manifest).unwrap();
/// assert!(code.contains("struct Person"));
/// ```
pub fn gen_decoder(
    cddl: &Cddl,
    root: Option<&str>,
    _config: &Config,
    manifest: &FeatureManifest,
) -> Result<String, GenError> {
    let ordered = collect_ordered(cddl, root);
    check_features_resolved(cddl, &ordered, manifest)?;

    let mut out = String::new();
    out.push_str("// Generated by cddl gen-decoder — do not edit by hand.\n");
    out.push_str("// Requires the `tps_minicbor` crate in your Cargo.toml.\n\n");

    for name in &ordered {
        if let Some(rule) = cddl.rules.iter().find(|r| &r.name == name) {
            let rule = prune_disabled_features(rule, manifest);
            emit_rule(&mut out, &rule, cddl);
            out.push('\n');
        }
    }

    Ok(out)
}


// ─── Code emission ─────────────────────────────────────────────────────────────

fn emit_rule(out: &mut String, rule: &Rule, cddl: &Cddl) {
    let kind = classify(rule);
    let rust_name = to_pascal_case(&rule.name);

    match kind {
        RuleKind::PreludeAlias => emit_alias(out, &rust_name, rule),
        RuleKind::Map => emit_map_struct(out, &rust_name, rule, cddl),
        RuleKind::FixedArray => emit_fixed_array(out, &rust_name, rule, cddl),
        RuleKind::RepeatedArray => emit_repeated_array(out, &rust_name, rule, cddl),
        RuleKind::Union => emit_union(out, &rust_name, rule, cddl),
        RuleKind::Unsupported => {
            out.push_str(&format!(
                "// TODO: unsupported rule `{}` — generate manually\n",
                rule.name
            ));
        }
    }
}

// ── Prelude alias ──────────────────────────────────────────────────────────────

fn emit_alias(out: &mut String, rust_name: &str, rule: &Rule) {
    use crate::gen_common::prelude_rust_type;
    if let RuleBody::Type(ty) = &rule.body
        && ty.choices.len() == 1
        && let Type2::Typename { name, .. } = &ty.choices[0].base
    {
        let rust_ty = prelude_rust_type(name);
        out.push_str(&format!("pub type {rust_name} = {rust_ty};\n"));
        return;
    }
    out.push_str(&format!("// TODO: unsupported alias `{}`\n", rule.name));
}

// ── Map struct ────────────────────────────────────────────────────────────────

fn emit_map_struct(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let group = match map_group(rule) {
        Some(g) => g,
        None => {
            out.push_str(&format!("// TODO: unsupported map rule `{}`\n", rule.name));
            return;
        }
    };

    if group.choices.len() != 1 {
        out.push_str(&format!(
            "// TODO: map rule `{}` has multiple choices — generate manually\n",
            rule.name
        ));
        return;
    }

    let choice = &group.choices[0];
    for entry in &choice.entries {
        if let GrpEntBody::Type(ty) = &entry.entry
            && ty.choices.len() == 1
        {
            let key_name = entry
                .key
                .as_ref()
                .and_then(map_key_repr)
                .map(|k| k.field_name())
                .unwrap_or_default();
            emit_regexp_todo(out, &ty.choices[0], &format!("`{key_name}` in `{rust_name}`"));
        }
    }
    let fields = map_fields(choice, cddl);
    let needs_lifetime = fields.iter().any(|f| f.needs_lifetime);
    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt = lt;
    let trait_lt = if needs_lifetime { "<'a>" } else { "<'_>" };

    // ── Struct definition ─────────────────────────────────────────────────────
    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!("pub struct {rust_name}{lt} {{\n"));
    for f in &fields {
        out.push_str(&format!("    pub {}: {},\n", f.rust_name, f.rust_type));
    }
    out.push_str("}\n\n");

    // ── Decode impl ───────────────────────────────────────────────────────────
    out.push_str(&format!(
        "impl{impl_lt} tps_minicbor::Decode{trait_lt} for {rust_name}{lt} {{\n"
    ));
    out.push_str("    fn decode(d: &mut tps_minicbor::Decoder");
    if needs_lifetime {
        out.push_str("<'a>");
    } else {
        out.push_str("<'_>");
    }
    out.push_str(") -> Result<Self, tps_minicbor::DecodeError> {\n");
    out.push_str("        let len = d.map_len()?;\n");
    for f in &fields {
        out.push_str(&format!(
            "        let mut {0}: {1} = None;\n",
            f.rust_name,
            f.option_type()
        ));
    }
    out.push_str("        for _ in 0..len {\n");
    out.push_str("            match d.next()? {\n");
    for f in &fields {
        out.push_str(&format!(
            "                {} => {} = Some({}),\n",
            f.key.decode_pattern(),
            f.rust_name,
            f.decode_expr
        ));
    }
    out.push_str("                _ => { d.next()?; }\n");
    out.push_str("            }\n");
    out.push_str("        }\n");
    out.push_str(&format!("        Ok({rust_name} {{\n"));
    for f in &fields {
        if let Some(default_literal) = &f.default_literal {
            out.push_str(&format!(
                "            {0}: {0}.unwrap_or({1}),\n",
                f.rust_name, default_literal
            ));
        } else if f.optional {
            out.push_str(&format!("            {},\n", f.rust_name));
        } else {
            out.push_str(&format!(
                "            {0}: {0}.ok_or(tps_minicbor::DecodeError::InvalidAdditionalInfo)?,\n",
                f.rust_name
            ));
        }
    }
    out.push_str("        })\n");
    out.push_str("    }\n");
    out.push_str("}\n");
}

struct MapField {
    rust_name: String,
    key: MapKeyRepr,
    rust_type: String,
    decode_expr: String,
    optional: bool,
    needs_lifetime: bool,
    default_literal: Option<String>,
}

impl MapField {
    fn option_type(&self) -> String {
        if self.optional {
            self.rust_type.clone()
        } else {
            format!("Option<{}>", self.rust_type)
        }
    }
}

fn map_fields(choice: &crate::ast::GrpChoice, cddl: &Cddl) -> Vec<MapField> {
    let mut fields = Vec::new();
    for entry in &choice.entries {
        let optional = matches!(entry.occur, Some(Occur::Optional));
        let key = match entry.key.as_ref().and_then(map_key_repr) {
            Some(k) => k,
            None => continue,
        };

        let default_literal = if optional {
            match &entry.entry {
                GrpEntBody::Type(ty) if ty.choices.len() == 1 => {
                    default_constraint(&ty.choices[0]).map(default_value_rust_literal)
                }
                _ => None,
            }
        } else {
            None
        };
        // A field with a literal `.default` is generated as plain `T`, not
        // `Option<T>`, with the default substituted when absent — so it's
        // decoded like a required field rather than a plain optional one.
        let field_optional = optional && default_literal.is_none();

        let (rust_type, decode_expr, needs_lifetime) = match &entry.entry {
            GrpEntBody::Type(ty) => type_to_rust_field(ty, cddl, field_optional),
            GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
                let rn = to_pascal_case(name);
                let nl = rule_needs_lifetime(name, cddl);
                let lt = if nl { "<'a>" } else { "" };
                (format!("{rn}{lt}"), format!("{rn}::decode(d)?"), nl)
            }
            _ => continue,
        };

        fields.push(MapField {
            rust_name: key.field_name(),
            key,
            rust_type,
            decode_expr,
            optional: field_optional,
            needs_lifetime,
            default_literal,
        });
    }
    fields
}

// ── Fixed array ───────────────────────────────────────────────────────────────

fn emit_fixed_array(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let group = match array_group(rule) {
        Some(g) => g,
        None => {
            out.push_str(&format!(
                "// TODO: unsupported array rule `{}`\n",
                rule.name
            ));
            return;
        }
    };
    if group.choices.len() != 1 {
        out.push_str(&format!(
            "// TODO: array rule `{}` has multiple choices\n",
            rule.name
        ));
        return;
    }

    let choice = &group.choices[0];
    let mut elem_types: Vec<(String, String, bool)> = Vec::new();

    for (i, entry) in choice.entries.iter().enumerate() {
        if entry.occur.is_some() {
            out.push_str(&format!(
                "// TODO: array rule `{}` has non-fixed occurrence\n",
                rule.name
            ));
            return;
        }
        if let GrpEntBody::Type(ty) = &entry.entry
            && ty.choices.len() == 1
        {
            emit_regexp_todo(out, &ty.choices[0], &format!("element {i} in `{rust_name}`"));
        }
        let (rt, de, nl) = match &entry.entry {
            GrpEntBody::Type(ty) => type_to_rust_field(ty, cddl, false),
            GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
                let rn = to_pascal_case(name);
                let nl = rule_needs_lifetime(name, cddl);
                let lt = if nl { "<'a>" } else { "" };
                (format!("{rn}{lt}"), format!("{rn}::decode(d)?"), nl)
            }
            _ => {
                out.push_str(&format!(
                    "// TODO: unsupported entry in array rule `{}`\n",
                    rule.name
                ));
                return;
            }
        };
        elem_types.push((rt, de, nl));
    }

    let count = elem_types.len();
    let needs_lifetime = elem_types.iter().any(|(_, _, nl)| *nl);
    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt = lt;
    let trait_lt = if needs_lifetime { "<'a>" } else { "<'_>" };

    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!("pub struct {rust_name}{lt}("));
    let type_parts: Vec<String> = elem_types
        .iter()
        .map(|(rt, _, _)| format!("pub {rt}"))
        .collect();
    out.push_str(&type_parts.join(", "));
    out.push_str(");\n\n");

    out.push_str(&format!(
        "impl{impl_lt} tps_minicbor::Decode{trait_lt} for {rust_name}{lt} {{\n"
    ));
    out.push_str("    fn decode(d: &mut tps_minicbor::Decoder");
    if needs_lifetime {
        out.push_str("<'a>");
    } else {
        out.push_str("<'_>");
    }
    out.push_str(") -> Result<Self, tps_minicbor::DecodeError> {\n");
    out.push_str("        let len = d.array_len()?;\n");
    out.push_str(&format!(
        "        if len != {count} {{ return Err(tps_minicbor::DecodeError::InvalidAdditionalInfo); }}\n"
    ));
    out.push_str(&format!("        Ok({rust_name}("));
    let decode_parts: Vec<String> = elem_types.iter().map(|(_, de, _)| de.clone()).collect();
    out.push_str(&decode_parts.join(", "));
    out.push_str("))\n");
    out.push_str("    }\n");
    out.push_str("}\n");
}

// ── Repeated array ────────────────────────────────────────────────────────────

fn emit_repeated_array(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let group = match array_group(rule) {
        Some(g) => g,
        None => {
            out.push_str(&format!(
                "// TODO: unsupported repeated array rule `{}`\n",
                rule.name
            ));
            return;
        }
    };
    if group.choices.len() != 1 || group.choices[0].entries.len() != 1 {
        out.push_str(&format!(
            "// TODO: complex repeated array rule `{}`\n",
            rule.name
        ));
        return;
    }

    let entry = &group.choices[0].entries[0];
    if let GrpEntBody::Type(ty) = &entry.entry
        && ty.choices.len() == 1
    {
        emit_regexp_todo(out, &ty.choices[0], &format!("elements of `{rust_name}`"));
    }
    let min: u64 = if matches!(entry.occur, Some(Occur::OneOrMore)) {
        1
    } else {
        0
    };

    let (elem_rust_type, elem_decode_expr, needs_lifetime) = match &entry.entry {
        GrpEntBody::Type(ty) => type_to_rust_field(ty, cddl, false),
        GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
            let rn = to_pascal_case(name);
            let nl = rule_needs_lifetime(name, cddl);
            let lt = if nl { "<'a>" } else { "" };
            (format!("{rn}{lt}"), format!("{rn}::decode(d)?"), nl)
        }
        _ => {
            out.push_str(&format!(
                "// TODO: unsupported element type in repeated array `{}`\n",
                rule.name
            ));
            return;
        }
    };

    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt = lt;
    let trait_lt = if needs_lifetime { "<'a>" } else { "<'_>" };

    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!(
        "pub struct {rust_name}{lt}(pub alloc::vec::Vec<{elem_rust_type}>);\n\n"
    ));

    out.push_str(&format!(
        "impl{impl_lt} tps_minicbor::Decode{trait_lt} for {rust_name}{lt} {{\n"
    ));
    out.push_str("    fn decode(d: &mut tps_minicbor::Decoder");
    if needs_lifetime {
        out.push_str("<'a>");
    } else {
        out.push_str("<'_>");
    }
    out.push_str(") -> Result<Self, tps_minicbor::DecodeError> {\n");
    out.push_str("        let len = d.array_len()?;\n");
    if min > 0 {
        out.push_str(&format!(
            "        if len < {min} {{ return Err(tps_minicbor::DecodeError::InvalidAdditionalInfo); }}\n"
        ));
    }
    out.push_str("        let mut items = alloc::vec::Vec::with_capacity(len as usize);\n");
    out.push_str(&format!(
        "        for _ in 0..len {{ items.push({elem_decode_expr}); }}\n"
    ));
    out.push_str(&format!("        Ok({rust_name}(items))\n"));
    out.push_str("    }\n");
    out.push_str("}\n");
}

// ── Union enum ────────────────────────────────────────────────────────────────

fn emit_union(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let ty = match &rule.body {
        RuleBody::Type(ty) => ty,
        _ => {
            out.push_str(&format!(
                "// TODO: unsupported union rule `{}`\n",
                rule.name
            ));
            return;
        }
    };

    let mut variants: Vec<UnionVariant> = Vec::new();
    let mut seen_majors: HashSet<String> = HashSet::new();

    for (i, t1) in ty.choices.iter().enumerate() {
        if t1.constraint.is_some() {
            out.push_str(&format!(
                "// TODO: choice {} in union `{}` has a constraint — skipped\n",
                i, rule.name
            ));
            continue;
        }
        let major_key = type2_major_key(&t1.base);
        if seen_majors.contains(&major_key) {
            out.push_str(&format!(
                "// TODO: choice {} in union `{}` shares major type `{}` — skipped (use first)\n",
                i, rule.name, major_key
            ));
            continue;
        }
        seen_majors.insert(major_key.clone());

        let (rust_type, needs_lt) = type2_to_rust_type(&t1.base, cddl);
        let variant_name = union_variant_name(i, t1, cddl);
        let item_pattern = type2_item_pattern(&t1.base, cddl);

        variants.push(UnionVariant {
            variant_name,
            rust_type,
            needs_lt,
            item_pattern,
        });
    }

    if variants.is_empty() {
        out.push_str(&format!("// TODO: empty union `{}`\n", rule.name));
        return;
    }

    let needs_lifetime = variants.iter().any(|v| v.needs_lt);
    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt = lt;
    let trait_lt = if needs_lifetime { "<'a>" } else { "<'_>" };

    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!("pub enum {rust_name}{lt} {{\n"));
    for v in &variants {
        out.push_str(&format!("    {}({}),\n", v.variant_name, v.rust_type));
    }
    out.push_str("}\n\n");

    out.push_str(&format!(
        "impl{impl_lt} tps_minicbor::Decode{trait_lt} for {rust_name}{lt} {{\n"
    ));
    out.push_str("    fn decode(d: &mut tps_minicbor::Decoder");
    if needs_lifetime {
        out.push_str("<'a>");
    } else {
        out.push_str("<'_>");
    }
    out.push_str(") -> Result<Self, tps_minicbor::DecodeError> {\n");
    out.push_str("        match d.next()? {\n");
    for v in &variants {
        out.push_str(&format!(
            "            {} => Ok({}::{}(v)),\n",
            v.item_pattern, rust_name, v.variant_name
        ));
    }
    out.push_str("            _ => Err(tps_minicbor::DecodeError::UnexpectedItem),\n");
    out.push_str("        }\n");
    out.push_str("    }\n");
    out.push_str("}\n");
}

struct UnionVariant {
    variant_name: String,
    rust_type: String,
    needs_lt: bool,
    item_pattern: String,
}

// ─── Type helpers (decoder-specific) ─────────────────────────────────────────

/// Resolves a map field's Rust type and per-key decode expression.
///
/// The decode expression yields a plain (non-`Option`) value of the field's
/// base type in both the required and optional cases — callers (the match arm
/// in `emit_map_struct`) wrap every `decode_expr` in `Some(...)` themselves to
/// track "was this key seen". For an optional field the resulting local's type
/// is already `Option<T>` (from `option_type`), so `decode_expr` here must
/// stay unwrapped or the assignment becomes `Option<Option<T>>`.
fn type_to_rust_field(ty: &Type, cddl: &Cddl, optional: bool) -> (String, String, bool) {
    if ty.choices.len() != 1 {
        return (
            "tps_minicbor::Item<'a>".to_string(),
            "d.next()?".to_string(),
            true,
        );
    }
    let t1 = &ty.choices[0];

    if let Some((target, is_seq)) = cbor_constraint(t1)
        && matches!(&t1.base, Type2::Typename { name, .. } if name == "bstr" || name == "bytes")
        && let Some((rt, nl)) = cbor_field_rust_type(target, is_seq, cddl)
    {
        let inner_expr = if is_seq {
            cborseq_decode_expr(target, cddl, "__bytes")
        } else {
            Some(format!("tps_minicbor::decode::<{rt}>(__bytes)?"))
        };
        if let Some(inner_expr) = inner_expr {
            let de = format!("{{ let __bytes = d.bytes()?; {inner_expr} }}");
            if optional {
                return (format!("Option<{rt}>"), de, nl);
            }
            return (rt, de, nl);
        }
    }

    let (mut rt, nl) = type2_to_rust_type(&t1.base, cddl);
    let de = type2_decode_expr(&t1.base, cddl);
    if optional {
        rt = format!("Option<{rt}>");
    }
    (rt, de, nl)
}

/// Generates a decode expression for a `.cborseq`-constrained field. The
/// controller's wire format has no array framing (RFC 8610 §3.8.4), so this
/// decodes each element directly from `bytes_expr` rather than delegating to
/// the controller rule's own `Decode` impl (which would expect/consume an
/// array-length header that isn't present here).
fn cborseq_decode_expr(target: &Type2, cddl: &Cddl, bytes_expr: &str) -> Option<String> {
    let name = match target {
        Type2::Typename {
            name, args: None, ..
        } => name,
        _ => return None,
    };
    let rule = cddl.rules.iter().find(|r| &r.name == name)?;
    let rust_name = to_pascal_case(name);

    match classify(rule) {
        RuleKind::RepeatedArray => {
            let group = array_group(rule)?;
            if group.choices.len() != 1 || group.choices[0].entries.len() != 1 {
                return None;
            }
            let entry = &group.choices[0].entries[0];
            let elem_expr = match &entry.entry {
                GrpEntBody::Type(ty) if ty.choices.len() == 1 => {
                    type2_decode_expr(&ty.choices[0].base, cddl)
                }
                GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
                    format!("{}::decode(d)?", to_pascal_case(name))
                }
                _ => return None,
            };
            Some(format!(
                "{{ let __seq = {bytes_expr}; let mut __sub = tps_minicbor::Decoder::new(__seq); \
                 let mut __items = alloc::vec::Vec::new(); \
                 while __sub.pos() < __seq.len() {{ let d = &mut __sub; __items.push({elem_expr}); }} \
                 {rust_name}(__items) }}"
            ))
        }
        RuleKind::FixedArray => {
            let group = array_group(rule)?;
            if group.choices.len() != 1 {
                return None;
            }
            let mut parts = Vec::new();
            for entry in &group.choices[0].entries {
                if entry.occur.is_some() {
                    return None;
                }
                let e = match &entry.entry {
                    GrpEntBody::Type(ty) if ty.choices.len() == 1 => {
                        type2_decode_expr(&ty.choices[0].base, cddl)
                    }
                    GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
                        format!("{}::decode(d)?", to_pascal_case(name))
                    }
                    _ => return None,
                };
                parts.push(e);
            }
            Some(format!(
                "{{ let __seq = {bytes_expr}; let mut __sub = tps_minicbor::Decoder::new(__seq); \
                 let d = &mut __sub; {rust_name}({}) }}",
                parts.join(", ")
            ))
        }
        _ => None,
    }
}

#[allow(clippy::only_used_in_recursion)]
fn type2_decode_expr(t2: &Type2, cddl: &Cddl) -> String {
    match t2 {
        Type2::Any(_) => "d.next()?".to_string(),
        Type2::Value(v) => match v {
            CddlValue::Int(n) if *n >= 0 => "d.uint()?".to_string(),
            CddlValue::Int(_) => "d.neg_int()?".to_string(),
            CddlValue::Float(_) => float_decode_expr(),
            CddlValue::Text(_) => "d.text()?".to_string(),
            CddlValue::Bytes(_) => "d.bytes()?".to_string(),
        },
        Type2::Typename { name, args, .. } => {
            if args.is_some() {
                return "d.next()?".to_string();
            }
            if is_prelude(name) {
                prelude_decode_expr(name)
            } else {
                format!("{}::decode(d)?", to_pascal_case(name))
            }
        }
        Type2::Tagged { inner, .. } => {
            if let Some(t1) = inner.choices.first() {
                let inner_expr = type2_decode_expr(&t1.base, cddl);
                format!("{{ let tagged = d.next_tag()?; let _ = tagged.tag; {inner_expr} }}")
            } else {
                "d.next()?".to_string()
            }
        }
        Type2::ParenType(inner) => {
            if inner.choices.len() == 1 {
                type2_decode_expr(&inner.choices[0].base, cddl)
            } else {
                "d.next()?".to_string()
            }
        }
        _ => "d.next()?".to_string(),
    }
}

fn prelude_decode_expr(name: &str) -> String {
    match name {
        "uint" => "d.uint()?",
        "int" => "d.next_int()?",
        "nint" => "d.neg_int()?",
        "tstr" | "text" | "tdate" | "time" | "uri" | "b64url" | "b64legacy" | "regexp"
        | "mime-message" => "d.text()?",
        "bstr" | "bytes" | "encoded-cbor" => "d.bytes()?",
        "bool" | "true" | "false" => "d.bool()?",
        "null" | "nil" => "{ d.null()?; () }",
        "float" | "float16" | "float32" | "float64" => return float_decode_expr(),
        _ => "d.next()?",
    }
    .to_string()
}

fn float_decode_expr() -> String {
    "match d.next_float()? { \
     tps_minicbor::Float::F16(b) => half::f16::from_bits(b).to_f64(), \
     tps_minicbor::Float::F32(b) => f32::from_bits(b) as f64, \
     tps_minicbor::Float::F64(b) => f64::from_bits(b) \
     }"
    .to_string()
}

