    fn generate(src: &str) -> String {
        let pairs = lex(src).unwrap_or_else(|e| panic!("lex: {e}"));
        let cddl = build_cddl(pairs).unwrap_or_else(|e| panic!("build: {e}"));
        let manifest = FeatureManifest::from_json("{}").unwrap();
        gen_encoder(&cddl, None, &Config::strict(), &manifest).unwrap()
    }

    fn generate_rule(src: &str, rule: &str) -> String {
        let pairs = lex(src).unwrap_or_else(|e| panic!("lex: {e}"));
        let cddl = build_cddl(pairs).unwrap_or_else(|e| panic!("build: {e}"));
        let manifest = FeatureManifest::from_json("{}").unwrap();
        gen_encoder(&cddl, Some(rule), &Config::strict(), &manifest).unwrap()
    }

