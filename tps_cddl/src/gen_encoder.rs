//! Phase 6: generate a `tps_minicbor`-based CBOR encoder from a CDDL schema.
//!
//! The public entry point is [`gen_encoder`].  It returns a Rust source string
//! that the caller can write to a file or print to stdout.

use crate::{
    Config,
    ast::{Cddl, GrpEntBody, Occur, Rule, RuleBody, Type1, Type2},
    feature_manifest::FeatureManifest,
    gen_common::{
        CborseqShape, GenError, MapKeyRepr, RuleKind, array_group, cbor_constraint,
        cbor_field_rust_type, cborseq_shape, check_features_resolved, classify, collect_ordered,
        default_constraint, default_value_rust_literal, emit_regexp_todo, map_group,
        map_key_repr, prelude_rust_type, prune_disabled_features, rule_needs_lifetime,
        to_pascal_case, type2_to_rust_type, union_variant_name,
    },
};

// ─── Public entry point ────────────────────────────────────────────────────────

/// Generate a Rust encoder source string for the given CDDL schema.
///
/// If `root` is `Some(name)`, only that rule and its transitive dependencies
/// are emitted.  If `root` is `None`, all rules are emitted.
///
/// Every `.feature` (RFC 9165 §4) name reachable in the emitted rule closure
/// must be resolved by `manifest`; an unresolved name is a hard error (see
/// [`GenError::UnresolvedFeatures`]). Choices resolved `disabled` are omitted
/// from the emitted union entirely; choices resolved `enabled` are emitted as
/// if unconstrained.
///
/// The returned string is valid Rust source that depends on the `tps_minicbor` crate.
///
/// # Examples
///
/// ```
/// use tps_cddl::{lex, build_cddl, gen_encoder, Config, FeatureManifest};
///
/// let pairs = lex("person = { name: tstr, age: uint }").unwrap();
/// let schema = build_cddl(pairs).unwrap();
/// let manifest = FeatureManifest::from_json("{}").unwrap();
/// let code = gen_encoder(&schema, None, &Config::strict(), &manifest).unwrap();
/// assert!(code.contains("struct Person"));
/// assert!(code.contains("EncodeItem"));
/// ```
pub fn gen_encoder(
    cddl: &Cddl,
    root: Option<&str>,
    _config: &Config,
    manifest: &FeatureManifest,
) -> Result<String, GenError> {
    let ordered = collect_ordered(cddl, root);
    check_features_resolved(cddl, &ordered, manifest)?;

    let mut out = String::new();
    out.push_str("// Generated by cddl gen-encoder — do not edit by hand.\n");
    out.push_str("// Requires the `tps_minicbor` crate in your Cargo.toml.\n\n");

    for name in &ordered {
        if let Some(rule) = cddl.rules.iter().find(|r| &r.name == name) {
            let rule = prune_disabled_features(rule, manifest);
            emit_rule(&mut out, &rule, cddl);
            out.push('\n');
        }
    }

    Ok(out)
}


// ─── Code emission ─────────────────────────────────────────────────────────────

fn emit_rule(out: &mut String, rule: &Rule, cddl: &Cddl) {
    let kind = classify(rule);
    let rust_name = to_pascal_case(&rule.name);

    match kind {
        RuleKind::PreludeAlias => emit_alias(out, &rust_name, rule),
        RuleKind::Map => emit_map_struct(out, &rust_name, rule, cddl),
        RuleKind::FixedArray => emit_fixed_array(out, &rust_name, rule, cddl),
        RuleKind::RepeatedArray => emit_repeated_array(out, &rust_name, rule, cddl),
        RuleKind::Union => emit_union(out, &rust_name, rule, cddl),
        RuleKind::Unsupported => {
            out.push_str(&format!(
                "// TODO: unsupported rule `{}` — generate manually\n",
                rule.name
            ));
        }
    }
}

// ── Prelude alias ──────────────────────────────────────────────────────────────

fn emit_alias(out: &mut String, rust_name: &str, rule: &Rule) {
    if let RuleBody::Type(ty) = &rule.body
        && ty.choices.len() == 1
        && let Type2::Typename { name, .. } = &ty.choices[0].base
    {
        let rust_ty = prelude_rust_type(name);
        out.push_str(&format!("pub type {rust_name} = {rust_ty};\n"));
        return;
    }
    out.push_str(&format!("// TODO: unsupported alias `{}`\n", rule.name));
}

// ── Map struct ────────────────────────────────────────────────────────────────

fn emit_map_struct(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let group = match map_group(rule) {
        Some(g) => g,
        None => {
            out.push_str(&format!("// TODO: unsupported map rule `{}`\n", rule.name));
            return;
        }
    };

    if group.choices.len() != 1 {
        out.push_str(&format!(
            "// TODO: map rule `{}` has multiple choices — generate manually\n",
            rule.name
        ));
        return;
    }

    let choice = &group.choices[0];
    for entry in &choice.entries {
        if let GrpEntBody::Type(ty) = &entry.entry
            && ty.choices.len() == 1
        {
            let key_name = entry
                .key
                .as_ref()
                .and_then(map_key_repr)
                .map(|k| k.field_name())
                .unwrap_or_default();
            emit_regexp_todo(out, &ty.choices[0], &format!("`{key_name}` in `{rust_name}`"));
        }
    }
    let fields = map_fields(choice, cddl);
    let needs_lifetime = fields.iter().any(|f| f.needs_lifetime);
    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt_for = if needs_lifetime {
        "impl<'a> tps_minicbor::EncodeItem for "
    } else {
        "impl tps_minicbor::EncodeItem for "
    };

    let n_required: usize = fields
        .iter()
        .filter(|f| !f.optional && f.default_literal.is_none())
        .count();
    let n_dynamic: usize = fields.iter().filter(|f| f.optional || f.default_literal.is_some()).count();

    // ── Struct definition ─────────────────────────────────────────────────────
    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!("pub struct {rust_name}{lt} {{\n"));
    for f in &fields {
        out.push_str(&format!("    pub {}: {},\n", f.rust_name, f.rust_type));
    }
    out.push_str("}\n\n");

    // ── EncodeItem impl ───────────────────────────────────────────────────────
    let lifetime_suffix = "<'_, N>";
    out.push_str(&format!("{impl_lt_for}{rust_name}{lt} {{\n"));

    // size()
    out.push_str(
        "    fn size(&self, s: &mut tps_minicbor::Sizer) -> Result<(), tps_minicbor::EncodeError> {\n",
    );
    if n_dynamic > 0 {
        let dyn_count_expr = fields
            .iter()
            .filter(|f| f.optional || f.default_literal.is_some())
            .map(|f| format!("({}) as u64", presence_expr(f)))
            .collect::<Vec<_>>()
            .join(" + ");
        out.push_str(&format!(
            "        let n_optional: u64 = {dyn_count_expr};\n"
        ));
        out.push_str(&format!("        s.map_len({n_required} + n_optional)?;\n"));
    } else {
        out.push_str(&format!("        s.map_len({n_required})?;\n"));
    }
    for f in &fields {
        if let Some(ov) = &f.cbor_override {
            if f.optional {
                out.push_str(&format!(
                    "        if let Some(v) = &self.{} {{ {} {} }}\n",
                    f.rust_name,
                    key_size_stmt(&f.key),
                    cbor_size_stmt("(*v)", ov)
                ));
            } else {
                out.push_str(&format!(
                    "        {} {}\n",
                    key_size_stmt(&f.key),
                    cbor_size_stmt(&format!("self.{}", f.rust_name), ov)
                ));
            }
        } else if f.optional {
            out.push_str(&format!(
                "        if let Some(v) = &self.{} {{ {} {}; }}\n",
                f.rust_name,
                key_size_stmt(&f.key),
                size_expr_for("v", &f.rust_type)
            ));
        } else if let Some(default_literal) = &f.default_literal {
            out.push_str(&format!(
                "        if self.{0} != {1} {{ {2} {3}; }}\n",
                f.rust_name,
                default_literal,
                key_size_stmt(&f.key),
                size_expr_for(&format!("self.{}", f.rust_name), &f.rust_type)
            ));
        } else {
            out.push_str(&format!(
                "        {} {};\n",
                key_size_stmt(&f.key),
                size_expr_for(&format!("self.{}", f.rust_name), &f.rust_type)
            ));
        }
    }
    out.push_str("        Ok(())\n");
    out.push_str("    }\n");

    // encode()
    out.push_str(&format!(
        "    fn encode<const N: usize>(&self, e: &mut tps_minicbor::Encoder{lifetime_suffix}) -> Result<(), tps_minicbor::EncodeError> {{\n"
    ));
    if n_dynamic > 0 {
        let dyn_count_expr = fields
            .iter()
            .filter(|f| f.optional || f.default_literal.is_some())
            .map(|f| format!("({}) as u64", presence_expr(f)))
            .collect::<Vec<_>>()
            .join(" + ");
        out.push_str(&format!(
            "        let n_optional: u64 = {dyn_count_expr};\n"
        ));
        out.push_str(&format!(
            "        let mut map = e.map_with_len({n_required} + n_optional)?;\n"
        ));
    } else {
        out.push_str(&format!(
            "        let mut map = e.map_with_len({n_required})?;\n"
        ));
    }
    for f in &fields {
        if let Some(ov) = &f.cbor_override {
            if f.optional {
                out.push_str(&format!(
                    "        if let Some(v) = &self.{} {{ {} }}\n",
                    f.rust_name,
                    cbor_encode_map_kv(&f.key, "(*v)", ov)
                ));
            } else {
                out.push_str(&format!(
                    "        {}\n",
                    cbor_encode_map_kv(&f.key, &format!("self.{}", f.rust_name), ov)
                ));
            }
        } else if f.optional {
            out.push_str(&format!(
                "        if let Some(v) = &self.{} {{ {}; }}\n",
                f.rust_name,
                encode_map_kv_ref(&f.key, "v")
            ));
        } else if let Some(default_literal) = &f.default_literal {
            out.push_str(&format!(
                "        if self.{0} != {1} {{ {2}; }}\n",
                f.rust_name,
                default_literal,
                encode_map_kv_ref(&f.key, &format!("&self.{}", f.rust_name))
            ));
        } else {
            out.push_str(&format!(
                "        {};\n",
                encode_map_kv_ref(&f.key, &format!("&self.{}", f.rust_name))
            ));
        }
    }
    out.push_str("        map.end()\n");
    out.push_str("    }\n");

    out.push_str("}\n");
}

fn presence_expr(f: &MapField) -> String {
    if f.optional {
        format!("self.{}.is_some()", f.rust_name)
    } else if let Some(default_literal) = &f.default_literal {
        format!("self.{} != {}", f.rust_name, default_literal)
    } else {
        "true".to_string()
    }
}

struct MapField {
    rust_name: String,
    key: MapKeyRepr,
    rust_type: String,
    optional: bool,
    needs_lifetime: bool,
    cbor_override: Option<CborOverride>,
    default_literal: Option<String>,
}

fn map_fields(choice: &crate::ast::GrpChoice, cddl: &Cddl) -> Vec<MapField> {
    let mut fields = Vec::new();
    for entry in &choice.entries {
        let occur_optional = matches!(entry.occur, Some(Occur::Optional));
        let key = match entry.key.as_ref().and_then(map_key_repr) {
            Some(k) => k,
            None => continue,
        };

        let default_literal = if occur_optional {
            match &entry.entry {
                GrpEntBody::Type(ty) if ty.choices.len() == 1 => {
                    default_constraint(&ty.choices[0]).map(default_value_rust_literal)
                }
                _ => None,
            }
        } else {
            None
        };
        // A field with a literal `.default` is generated as plain `T`, not
        // `Option<T>` — the encoder auto-omits the map entry when the
        // current value equals the default instead of gating on `Option`.
        let optional = occur_optional && default_literal.is_none();

        let (rust_type, needs_lifetime, cbor_override) = match &entry.entry {
            GrpEntBody::Type(ty) => {
                if ty.choices.len() == 1 {
                    if let Some((rt, nl, ov)) = cbor_override_for(&ty.choices[0], cddl) {
                        let rt = if optional {
                            format!("Option<{rt}>")
                        } else {
                            rt
                        };
                        (rt, nl, Some(ov))
                    } else {
                        let (mut rt, nl) = type2_to_rust_type(&ty.choices[0].base, cddl);
                        if optional {
                            rt = format!("Option<{rt}>");
                        }
                        (rt, nl, None)
                    }
                } else {
                    ("tps_minicbor::Item<'a>".to_string(), true, None)
                }
            }
            GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
                let rn = to_pascal_case(name);
                let nl = rule_needs_lifetime(name, cddl);
                let lt = if nl { "<'a>" } else { "" };
                let rt = if optional {
                    format!("Option<{rn}{lt}>")
                } else {
                    format!("{rn}{lt}")
                };
                (rt, nl, None)
            }
            _ => continue,
        };

        fields.push(MapField {
            rust_name: key.field_name(),
            key,
            rust_type,
            optional,
            needs_lifetime,
            cbor_override,
            default_literal,
        });
    }
    fields
}

// ── Fixed array ───────────────────────────────────────────────────────────────

fn emit_fixed_array(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let group = match array_group(rule) {
        Some(g) => g,
        None => {
            out.push_str(&format!(
                "// TODO: unsupported array rule `{}`\n",
                rule.name
            ));
            return;
        }
    };
    if group.choices.len() != 1 {
        out.push_str(&format!(
            "// TODO: array rule `{}` has multiple choices\n",
            rule.name
        ));
        return;
    }

    let choice = &group.choices[0];
    let mut elem_types: Vec<(String, bool, Option<CborOverride>)> = Vec::new();

    for (i, entry) in choice.entries.iter().enumerate() {
        if entry.occur.is_some() {
            out.push_str(&format!(
                "// TODO: array rule `{}` has non-fixed occurrence\n",
                rule.name
            ));
            return;
        }
        if let GrpEntBody::Type(ty) = &entry.entry
            && ty.choices.len() == 1
        {
            emit_regexp_todo(out, &ty.choices[0], &format!("element {i} in `{rust_name}`"));
        }
        let (rt, nl, ov) = match &entry.entry {
            GrpEntBody::Type(ty) => {
                if ty.choices.len() == 1 {
                    if let Some((rt, nl, ov)) = cbor_override_for(&ty.choices[0], cddl) {
                        (rt, nl, Some(ov))
                    } else {
                        let (rt, nl) = type2_to_rust_type(&ty.choices[0].base, cddl);
                        (rt, nl, None)
                    }
                } else {
                    ("tps_minicbor::Item<'a>".to_string(), true, None)
                }
            }
            GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
                let rn = to_pascal_case(name);
                let nl = rule_needs_lifetime(name, cddl);
                let lt = if nl { "<'a>" } else { "" };
                (format!("{rn}{lt}"), nl, None)
            }
            _ => {
                out.push_str(&format!(
                    "// TODO: unsupported entry in array rule `{}`\n",
                    rule.name
                ));
                return;
            }
        };
        elem_types.push((rt, nl, ov));
    }

    let count = elem_types.len();
    let needs_lifetime = elem_types.iter().any(|(_, nl, _)| *nl);
    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt_for = if needs_lifetime {
        "impl<'a> tps_minicbor::EncodeItem for "
    } else {
        "impl tps_minicbor::EncodeItem for "
    };
    let lifetime_suffix = "<'_, N>";

    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!("pub struct {rust_name}{lt}("));
    let type_parts: Vec<String> = elem_types
        .iter()
        .map(|(rt, _, _)| format!("pub {rt}"))
        .collect();
    out.push_str(&type_parts.join(", "));
    out.push_str(");\n\n");

    out.push_str(&format!("{impl_lt_for}{rust_name}{lt} {{\n"));

    // size()
    out.push_str(
        "    fn size(&self, s: &mut tps_minicbor::Sizer) -> Result<(), tps_minicbor::EncodeError> {\n",
    );
    out.push_str(&format!("        s.array_len({count})?;\n"));
    for (i, (rt, _, ov)) in elem_types.iter().enumerate() {
        if let Some(ov) = ov {
            out.push_str(&format!("        {}\n", cbor_size_stmt(&format!("self.{i}"), ov)));
        } else {
            out.push_str(&format!(
                "        {};\n",
                size_expr_for(&format!("self.{i}"), rt)
            ));
        }
    }
    out.push_str("        Ok(())\n");
    out.push_str("    }\n");

    // encode()
    out.push_str(&format!(
        "    fn encode<const N: usize>(&self, e: &mut tps_minicbor::Encoder{lifetime_suffix}) -> Result<(), tps_minicbor::EncodeError> {{\n"
    ));
    out.push_str(&format!(
        "        let mut arr = e.array_with_len({count})?;\n"
    ));
    for (i, (_, _, ov)) in elem_types.iter().enumerate() {
        if let Some(ov) = ov {
            out.push_str(&format!(
                "        {}\n",
                cbor_encode_arr_elem(&format!("self.{i}"), ov)
            ));
        } else {
            out.push_str(&format!(
                "        {};\n",
                encode_arr_elem_ref(&format!("&self.{i}"))
            ));
        }
    }
    out.push_str("        arr.end()\n");
    out.push_str("    }\n");

    out.push_str("}\n");
}

// ── Repeated array ────────────────────────────────────────────────────────────

fn emit_repeated_array(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let group = match array_group(rule) {
        Some(g) => g,
        None => {
            out.push_str(&format!(
                "// TODO: unsupported repeated array rule `{}`\n",
                rule.name
            ));
            return;
        }
    };
    if group.choices.len() != 1 || group.choices[0].entries.len() != 1 {
        out.push_str(&format!(
            "// TODO: complex repeated array rule `{}`\n",
            rule.name
        ));
        return;
    }

    let entry = &group.choices[0].entries[0];
    if let GrpEntBody::Type(ty) = &entry.entry
        && ty.choices.len() == 1
    {
        emit_regexp_todo(out, &ty.choices[0], &format!("elements of `{rust_name}`"));
    }
    let (elem_rust_type, needs_lifetime, elem_cbor_override) = match &entry.entry {
        GrpEntBody::Type(ty) => {
            if ty.choices.len() == 1 {
                if let Some((rt, nl, ov)) = cbor_override_for(&ty.choices[0], cddl) {
                    (rt, nl, Some(ov))
                } else {
                    let (rt, nl) = type2_to_rust_type(&ty.choices[0].base, cddl);
                    (rt, nl, None)
                }
            } else {
                ("tps_minicbor::Item<'a>".to_string(), true, None)
            }
        }
        GrpEntBody::GroupRef { name, args, .. } if args.is_none() => {
            let rn = to_pascal_case(name);
            let nl = rule_needs_lifetime(name, cddl);
            let lt = if nl { "<'a>" } else { "" };
            (format!("{rn}{lt}"), nl, None)
        }
        _ => {
            out.push_str(&format!(
                "// TODO: unsupported element type in repeated array `{}`\n",
                rule.name
            ));
            return;
        }
    };

    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt_for = if needs_lifetime {
        "impl<'a> tps_minicbor::EncodeItem for "
    } else {
        "impl tps_minicbor::EncodeItem for "
    };
    let lifetime_suffix = "<'_, N>";

    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!(
        "pub struct {rust_name}{lt}(pub alloc::vec::Vec<{elem_rust_type}>);\n\n"
    ));

    out.push_str(&format!("{impl_lt_for}{rust_name}{lt} {{\n"));

    // size()
    out.push_str(
        "    fn size(&self, s: &mut tps_minicbor::Sizer) -> Result<(), tps_minicbor::EncodeError> {\n",
    );
    out.push_str("        s.array_len(self.0.len() as u64)?;\n");
    if let Some(ov) = &elem_cbor_override {
        out.push_str(&format!(
            "        for item in &self.0 {{ {} }}\n",
            cbor_size_stmt("*item", ov)
        ));
    } else {
        out.push_str(&format!(
            "        for item in &self.0 {{ {}; }}\n",
            size_expr_for("item", &elem_rust_type)
        ));
    }
    out.push_str("        Ok(())\n");
    out.push_str("    }\n");

    // encode()
    out.push_str(&format!(
        "    fn encode<const N: usize>(&self, e: &mut tps_minicbor::Encoder{lifetime_suffix}) -> Result<(), tps_minicbor::EncodeError> {{\n"
    ));
    out.push_str("        let mut arr = e.array_with_len(self.0.len() as u64)?;\n");
    if let Some(ov) = &elem_cbor_override {
        out.push_str(&format!(
            "        for item in &self.0 {{ {} }}\n",
            cbor_encode_arr_elem("*item", ov)
        ));
    } else {
        out.push_str(&format!(
            "        for item in &self.0 {{ {}; }}\n",
            encode_arr_elem_ref("item")
        ));
    }
    out.push_str("        arr.end()\n");
    out.push_str("    }\n");

    out.push_str("}\n");
}

// ── Union enum ────────────────────────────────────────────────────────────────

fn emit_union(out: &mut String, rust_name: &str, rule: &Rule, cddl: &Cddl) {
    let ty = match &rule.body {
        RuleBody::Type(ty) => ty,
        _ => {
            out.push_str(&format!(
                "// TODO: unsupported union rule `{}`\n",
                rule.name
            ));
            return;
        }
    };

    struct Variant {
        name: String,
        rust_type: String,
        needs_lt: bool,
    }

    let mut variants: Vec<Variant> = Vec::new();
    for (i, t1) in ty.choices.iter().enumerate() {
        if t1.constraint.is_some() {
            out.push_str(&format!(
                "// TODO: choice {i} in union `{}` has a constraint — skipped\n",
                rule.name
            ));
            continue;
        }
        let (rust_type, needs_lt) = type2_to_rust_type(&t1.base, cddl);
        let variant_name = union_variant_name(i, t1, cddl);
        variants.push(Variant {
            name: variant_name,
            rust_type,
            needs_lt,
        });
    }

    if variants.is_empty() {
        out.push_str(&format!("// TODO: empty union `{}`\n", rule.name));
        return;
    }

    let needs_lifetime = variants.iter().any(|v| v.needs_lt);
    let lt = if needs_lifetime { "<'a>" } else { "" };
    let impl_lt_for = if needs_lifetime {
        "impl<'a> tps_minicbor::EncodeItem for "
    } else {
        "impl tps_minicbor::EncodeItem for "
    };
    let lifetime_suffix = "<'_, N>";

    out.push_str("#[derive(Debug)]\n");
    out.push_str(&format!("pub enum {rust_name}{lt} {{\n"));
    for v in &variants {
        out.push_str(&format!("    {}({}),\n", v.name, v.rust_type));
    }
    out.push_str("}\n\n");

    out.push_str(&format!("{impl_lt_for}{rust_name}{lt} {{\n"));

    // size()
    out.push_str(
        "    fn size(&self, s: &mut tps_minicbor::Sizer) -> Result<(), tps_minicbor::EncodeError> {\n",
    );
    out.push_str("        match self {\n");
    for v in &variants {
        let se = size_expr_for("v", &v.rust_type);
        out.push_str(&format!(
            "            {}::{}(v) => {{ {}; }}\n",
            rust_name, v.name, se
        ));
    }
    out.push_str("        }\n");
    out.push_str("        Ok(())\n");
    out.push_str("    }\n");

    // encode()
    out.push_str(&format!(
        "    fn encode<const N: usize>(&self, e: &mut tps_minicbor::Encoder{lifetime_suffix}) -> Result<(), tps_minicbor::EncodeError> {{\n"
    ));
    out.push_str("        match self {\n");
    for v in &variants {
        let ee = encode_standalone_ref("v");
        out.push_str(&format!(
            "            {}::{}(v) => {{ {}; }}\n",
            rust_name, v.name, ee
        ));
    }
    out.push_str("        }\n");
    out.push_str("        Ok(())\n");
    out.push_str("    }\n");

    out.push_str("}\n");
}

// ─── Encode helpers ───────────────────────────────────────────────────────────

/// Generate a `{expr}.size(s)?` size expression for a field value.
///
/// Calls [`tps_minicbor::EncodeItem::size`] directly on `expr` rather than going
/// through `Sizer::insert`, which takes its argument by value: that would require
/// every field type to be `Copy` (fields are only ever reachable as `&self.field`
/// or an already-bound `&T` loop/match variable) and has no blanket impl for
/// `&T` beyond the special-cased `&str`/`&[u8]`. Calling the trait method
/// directly works uniformly for owned places and existing references alike.
fn size_expr_for(expr: &str, _rust_type: &str) -> String {
    format!("{expr}.size(s)?")
}

/// Generate a `map.insert_key_value_ref("key", ref_expr)` expression for a map
/// field. `ref_expr` must already be a `&T` expression — callers pass
/// `&self.field` for required fields (a bare place) or the loop/match-bound `v`
/// for optional fields (already a reference from `&self.field` destructuring).
fn encode_map_kv_ref(key: &MapKeyRepr, ref_expr: &str) -> String {
    let key_expr = key.literal_expr();
    format!("map.insert_key_value_ref({key_expr}, {ref_expr})?")
}

/// Generate a `s.text("key")?` or `s.bytes(b"key")?` statement sizing a map key.
fn key_size_stmt(key: &MapKeyRepr) -> String {
    match key {
        MapKeyRepr::Text(_) => format!("s.text({})?;", key.literal_expr()),
        MapKeyRepr::Bytes(_) => format!("s.bytes({})?;", key.literal_expr()),
    }
}

/// Generate an `arr.insert_ref(ref_expr)` expression for array elements.
/// See [`encode_map_kv_ref`] for the `ref_expr` calling convention.
fn encode_arr_elem_ref(ref_expr: &str) -> String {
    format!("arr.insert_ref({ref_expr})?")
}

/// Generate a top-level `e.insert_ref(ref_expr)` expression.
/// See [`encode_map_kv_ref`] for the `ref_expr` calling convention.
fn encode_standalone_ref(ref_expr: &str) -> String {
    format!("e.insert_ref({ref_expr})?")
}

// ─── `.cbor` / `.cborseq` field encoding (RFC 8610 §3.8.4) ──────────────────────

/// A field whose CDDL type is `.cbor`/`.cborseq`-constrained: its wire
/// representation is a byte string, but it's generated as the controller's own
/// Rust type (see [`cbor_field_rust_type`]). Encoding it means materializing
/// the controller value's nested CBOR encoding into a scratch buffer first,
/// then writing that buffer as the field's byte-string content — `.cbor`'s
/// buffer is the controller's own single-item encoding; `.cborseq`'s buffer is
/// its elements' encodings concatenated with no array framing at all.
struct CborOverride {
    /// The controller's array shape for `.cborseq`, or `None` for `.cbor`.
    seq_shape: Option<CborseqShape>,
}

/// If `t1`'s constraint is a `.cbor`/`.cborseq` control operator that codegen
/// supports (see [`cbor_field_rust_type`]), resolves the field's Rust type
/// plus a [`CborOverride`] describing how to encode it. Returns `None` for any
/// unconstrained field, or one with an unsupported controller shape — callers
/// fall back to the ordinary unconstrained `bstr` codegen path.
fn cbor_override_for(t1: &Type1, cddl: &Cddl) -> Option<(String, bool, CborOverride)> {
    let (target, is_seq) = cbor_constraint(t1)?;
    if !matches!(&t1.base, Type2::Typename { name, .. } if name == "bstr" || name == "bytes") {
        return None;
    }
    let (rt, nl) = cbor_field_rust_type(target, is_seq, cddl)?;
    let seq_shape = if is_seq {
        Some(cborseq_shape(target, cddl)?)
    } else {
        None
    };
    Some((rt, nl, CborOverride { seq_shape }))
}

/// Generates a block expression evaluating to `alloc::vec::Vec<u8>`: the
/// nested-CBOR encoding of `expr` (a `.cbor` field) or the concatenated,
/// unframed encodings of `expr`'s elements (a `.cborseq` field).
fn cbor_bytes_block(expr: &str, ov: &CborOverride) -> String {
    match &ov.seq_shape {
        None => format!(
            "{{ let mut __buf = alloc::vec::Vec::new(); \
             __buf.resize(tps_minicbor::encoded_len(&{expr})?, 0); \
             tps_minicbor::encode(&{expr}, &mut __buf)?; \
             __buf }}"
        ),
        Some(CborseqShape::Repeated) => format!(
            "{{ let mut __buf: alloc::vec::Vec<u8> = alloc::vec::Vec::new(); \
             for __item in &({expr}).0 {{ \
             let mut __item_buf = alloc::vec::Vec::new(); \
             __item_buf.resize(tps_minicbor::encoded_len(__item)?, 0); \
             tps_minicbor::encode(__item, &mut __item_buf)?; \
             __buf.extend_from_slice(&__item_buf); \
             }} __buf }}"
        ),
        Some(CborseqShape::Fixed(count)) => {
            let mut s =
                String::from("{ let mut __buf: alloc::vec::Vec<u8> = alloc::vec::Vec::new(); ");
            for i in 0..*count {
                s.push_str(&format!(
                    "{{ let mut __item_buf = alloc::vec::Vec::new(); \
                     __item_buf.resize(tps_minicbor::encoded_len(&({expr}).{i})?, 0); \
                     tps_minicbor::encode(&({expr}).{i}, &mut __item_buf)?; \
                     __buf.extend_from_slice(&__item_buf); }} "
                ));
            }
            s.push_str("__buf }");
            s
        }
    }
}

/// Generate a `s.bytes(&buf)?;` size statement for a `.cbor`/`.cborseq` field.
fn cbor_size_stmt(expr: &str, ov: &CborOverride) -> String {
    format!(
        "{{ let __buf = {}; s.bytes(&__buf)?; }}",
        cbor_bytes_block(expr, ov)
    )
}

/// Generate a `map.insert_key_value_ref(key, &buf)?;` encode statement for a
/// `.cbor`/`.cborseq` map field.
fn cbor_encode_map_kv(key: &MapKeyRepr, expr: &str, ov: &CborOverride) -> String {
    let key_expr = key.literal_expr();
    format!(
        "{{ let __buf = {}; map.insert_key_value_ref({key_expr}, &__buf[..])?; }}",
        cbor_bytes_block(expr, ov)
    )
}

/// Generate an `arr.insert_ref(&buf)?;` encode statement for a `.cbor`/
/// `.cborseq` array element.
fn cbor_encode_arr_elem(expr: &str, ov: &CborOverride) -> String {
    format!(
        "{{ let __buf = {}; arr.insert_ref(&__buf[..])?; }}",
        cbor_bytes_block(expr, ov)
    )
}

